const LanguageContext = createContext<LanguageContextType>({
  lang: 'bn',
  setLanguage: () => {},
  isRtl: false,
  t: () => '',
  ui: UI_DICTIONARY['bn'],
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Language>(() => {
    const saved = localStorage.getItem('portfolio_lang') as Language;
    return saved && ['bn', 'en', 'ar', 'ur'].includes(saved) ? saved : 'bn';
  });

  const isRtl = lang === 'ar' || lang === 'ur';

  const setLanguage = (newLang: Language) => {
    setLangState(newLang);
    localStorage.setItem('portfolio_lang', newLang);
  };

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
  }, [lang, isRtl]);

  const t = (value: LocalizedString | string | undefined, fallback = ''): string => {
    if (!value) return fallback;
    if (typeof value === 'string') return value;
    return value[lang] || value.en || value.bn || fallback;
  };

  const ui = UI_DICTIONARY[lang] || UI_DICTIONARY['bn'];

  return (
    <LanguageContext.Provider value={{ lang, setLanguage, isRtl, t, ui }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
